// The kit's pure parts: what an export carries, the steps a setup runs, how
// settings merge, and which files never leave this machine.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { DENY, exportManifest, newestVsix, isSecretFile, launchAgent, mergeSettings, oldRcPids, planSetup, RC_NAME, rcArgs, rcExitNote, rcPattern, rulesAction, rulesTargets, staleRc, withDeny, withTrust } from './kit.mjs'

const settings = {
  model: 'opus', theme: 'dark', autoCompactWindow: 200000, remoteControlAtStartup: true,
  env: { OPENROUTER_API_KEY: 'sk-or-v1-xxxxxxxxxxxxxxxxxxxx' }, permissions: { allow: ['Bash(ls:*)'] }, hooks: { Stop: [] },
  enabledPlugins: { 'superpowers@superpowers-dev': true, 'auth0@claude-plugins-official': false, 'usage-meter@kenneth-mods': true },
}
// The shape of ~/.claude/plugins/known_marketplaces.json: the source nested, beside local paths.
const known = {
  'superpowers-dev': { source: { source: 'git', url: 'https://github.com/obra/superpowers.git' }, installLocation: '/Users/k/.claude/plugins/marketplaces/superpowers-dev', lastUpdated: '2026-05-28T07:24:36.640Z' },
  'claude-plugins-official': { source: { source: 'github', repo: 'anthropics/claude-plugins-official' }, installLocation: '/Users/k/.claude/plugins/marketplaces/claude-plugins-official', lastUpdated: '2026-10-23T09:02:02.825Z' },
  'kenneth-mods': { source: { source: 'directory', path: '/Users/k/Documents/GitHub/claude-mods' }, installLocation: '/Users/k/Documents/GitHub/claude-mods', lastUpdated: '2026-10-22T00:00:00.000Z' },
}

test('an export carries plugins, marketplaces, skills and only the safe settings', () => {
  const m = exportManifest({ settings, known, skills: ['phone', 'synced'], archived: ['drei'], presets: ['armasu-copy-check.json'], now: 0 })
  assert.deepEqual(m.plugins, settings.enabledPlugins)
  assert.deepEqual(m.marketplaces['kenneth-mods'], { source: 'kit' })
  assert.deepEqual(m.marketplaces['superpowers-dev'], { source: 'git', url: 'https://github.com/obra/superpowers.git' })
  // No local paths travel: they name this machine's user and mean nothing on the other one.
  assert.ok(!JSON.stringify(m).includes('/Users/k'))
  assert.deepEqual(m.skills, ['phone'])
  assert.deepEqual(m.skillsArchived, ['drei'])
  assert.equal(m.settings.env, undefined)
  assert.equal(m.settings.permissions, undefined)
  assert.equal(m.settings.hooks, undefined)
  assert.equal(m.settings.autoCompactWindow, 200000)
  assert.deepEqual(m.settings.statusLine, { type: 'command', command: 'node <KIT>/statusline.mjs' })
})

test('a setup adds marketplaces, installs plugins, turns off the ones that were off, then the rest', () => {
  const m = exportManifest({ settings, known, skills: ['phone'], archived: [], presets: [], now: 0 })
  const steps = planSetup(m, { kit: '/home/k/claude-mods/kit', vsix: 'switchboard-0.10.0.vsix' })
  const cmds = steps.filter(s => s.kind === 'run').map(s => s.args.join(' '))
  assert.ok(cmds.includes('plugin marketplace add https://github.com/obra/superpowers.git'))
  assert.ok(cmds.includes('plugin marketplace add anthropics/claude-plugins-official'))
  assert.ok(cmds.includes('plugin marketplace add /home/k/claude-mods'))
  assert.ok(cmds.indexOf('plugin install auth0@claude-plugins-official') < cmds.indexOf('plugin disable auth0@claude-plugins-official'))
  assert.ok(!cmds.includes('plugin disable superpowers@superpowers-dev'))
  assert.ok(steps.some(s => s.kind === 'copy' && s.what === 'skills'))
  assert.ok(steps.some(s => s.kind === 'settings'))
  assert.ok(steps.some(s => s.kind === 'run' && s.cmd === 'code' && s.args.join(' ').includes('--install-extension')))
})

test('settings merge keeps what the machine has and points the status line at this kit', () => {
  const merged = mergeSettings({ theme: 'light', hooks: { Stop: [1] } }, { theme: 'dark', statusLine: { type: 'command', command: 'node <KIT>/statusline.mjs' } }, 'C:\\Users\\k\\claude-mods\\kit')
  assert.equal(merged.theme, 'dark')
  assert.deepEqual(merged.hooks, { Stop: [1] })
  assert.equal(merged.statusLine.command, 'node "C:/Users/k/claude-mods/kit/statusline.mjs"')
})

test('files that look like secrets stay behind', () => {
  assert.equal(isSecretFile('.env.local', 'A=1'), true)
  assert.equal(isSecretFile('id_ed25519.pem', ''), true)
  assert.equal(isSecretFile('notes.md', 'key: sk-or-v1-0123456789abcdef0123456789'), true)
  assert.equal(isSecretFile('credentials.md', 'How the SDK finds credentials: the default chain.'), false)
  assert.equal(isSecretFile('SKILL.md', '# Phone\nCalls the owner.'), false)
})

test('rules go to Claude and Codex with a generated header', () => {
  const t = rulesTargets('/h', '# Rules\n')
  assert.deepEqual(t.map(x => x.path), ['/h/.claude/CLAUDE.md', '/h/.codex/AGENTS.md'])
  assert.match(t[0].text, /^<!-- generated by claude-mods\/kit\/setup\.mjs/)
  assert.ok(t[1].text.endsWith('# Rules\n'))
})

test('rules carry the version line Switchboard reads', () => {
  const t = rulesTargets('/h', '# Rules\n', '2026-10-28T10:00:00Z')
  assert.match(t[0].text, /^<!-- generated by .*-->\n<!-- rules-version: 2026-10-28T10:00:00Z sha256:[0-9a-f]{12} -->\n\n# Rules\n$/)
})

test('rules never downgrade newer generated rules', () => {
  const v = '2026-10-28T10:00:00Z'
  const newer = rulesTargets('/h', '# Newer\n', '2026-11-01T00:00:00Z')[0].text
  assert.equal(rulesAction(newer, '# Rules\n', v), 'skip')
  assert.equal(rulesAction(rulesTargets('/h', '# Old\n', '2026-01-01T00:00:00Z')[0].text, '# Rules\n', v), 'write')
  assert.equal(rulesAction(undefined, '# Rules\n', v), 'write')
  assert.equal(rulesAction('# Hand-written\n', '# Rules\n', v), 'write')
})

test('deny list merged once, existing entries kept', () => {
  const s = withDeny({ permissions: { deny: ['Bash(curl:*)'], defaultMode: 'bypassPermissions' } })
  assert.equal(s.permissions.defaultMode, 'bypassPermissions')
  assert.deepEqual(s.permissions.deny, ['Bash(curl:*)', ...DENY])
  assert.deepEqual(withDeny(s).permissions.deny, s.permissions.deny)
})

test('launchAgent runs rc-servers.mjs at login', () => {
  const xml = launchAgent('/usr/local/bin/node', '/k/rc-servers.mjs')
  assert.match(xml, /<key>RunAtLoad<\/key>\s*<true\/>/)
  assert.match(xml, /\/k\/rc-servers\.mjs/)
})

test('a rerun drops the deny entries an older kit wrote', () => {
  const s = withDeny({ permissions: { deny: ['Bash(curl:*)', 'Bash(rm -rf ~:*)', 'Bash(rm -rf /:*)', 'Read(**/.env*)'] } })
  assert.deepEqual(s.permissions.deny, ['Bash(curl:*)', ...DENY])
  assert.ok(!DENY.includes('Bash(rm -rf /*)'), 'a trailing * would also refuse rm -rf /tmp/x')
})

test('one Remote Control server for the machine, sharing its folder, in bypass mode', () => {
  assert.equal(RC_NAME, 'Mac')
  assert.deepEqual(rcArgs(), ['remote-control', '--name', 'Mac', '--spawn', 'same-dir', '--permission-mode', 'bypassPermissions'])
  assert.ok(new RegExp(rcPattern(RC_NAME)).test(`claude ${rcArgs().join(' ')}`))
  assert.ok(!new RegExp(rcPattern(RC_NAME)).test('claude remote-control --name agent-flow --spawn worktree'))
})

test('per-repo servers from before the single one are picked out to stop, Mac is kept', () => {
  const out = '101 claude remote-control --name agent-flow --spawn worktree --permission-mode bypassPermissions\n102 claude remote-control --name Mac --spawn same-dir --permission-mode bypassPermissions\n103 claude remote-control --name Mac2 --spawn worktree\n104 node pgrep remote-control --name\n'
  assert.deepEqual(oldRcPids(out), [101, 103])
  assert.deepEqual(oldRcPids(''), [])
})

test('the running-server check matches the name literally and whole', () => {
  const re = new RegExp(rcPattern('a.b'))
  assert.ok(re.test('claude remote-control --name a.b --spawn worktree'))
  assert.ok(re.test('claude remote-control --name a.b'))
  assert.ok(!re.test('claude remote-control --name axb --spawn worktree'))
  assert.ok(!re.test('claude remote-control --name a.bc --spawn worktree'))
})

test('a server that exited says why', () => {
  assert.equal(rcExitNote('Mac', '/g', 'Error: Workspace not trusted.'), 'Mac: not trusted yet, run `claude` once in /g and accept the trust prompt')
  assert.equal(rcExitNote('QR', '/g/QR', 'Error: Workspace not trusted. Please run `claude` in /g/QR first'), 'QR: not trusted yet, run `claude` once in /g/QR and accept the trust prompt')
  assert.equal(rcExitNote('QR', '/g/QR', '\nError: not signed in\nmore'), 'QR: Error: not signed in')
  assert.equal(rcExitNote('QR', '/g/QR', ''), 'QR: exited, see its log')
})

test('the GitHub folder is marked trusted, so the server starts there without a prompt', () => {
  const after = withTrust({ projects: {} }, ['/u/Documents/GitHub'])
  assert.deepEqual(after.projects, { '/u/Documents/GitHub': { hasTrustDialogAccepted: true } })
})

test('repos are marked trusted, other project settings kept, nothing else touched', () => {
  const before = { numStartups: 3, projects: { '/g/A': { hasTrustDialogAccepted: false, allowedTools: ['x'] }, '/o': { hasTrustDialogAccepted: false } } }
  const after = withTrust(before, ['/g/A', '/g/B'])
  assert.deepEqual(after.projects['/g/A'], { hasTrustDialogAccepted: true, allowedTools: ['x'] })
  assert.deepEqual(after.projects['/g/B'], { hasTrustDialogAccepted: true })
  assert.deepEqual(after.projects['/o'], { hasTrustDialogAccepted: false })
  assert.equal(after.numStartups, 3)
  assert.equal(withTrust(after, ['/g/A', '/g/B']), after, 'no change returns the same object, so nothing is written')
})

test('a server started before bypass mode is restarted', () => {
  assert.ok(staleRc('claude remote-control --name A --spawn worktree --permission-mode acceptEdits'))
  assert.ok(!staleRc('claude remote-control --name A --spawn worktree --permission-mode bypassPermissions'))
})

test('role subagents travel: an export lists the .md files, a setup installs them', () => {
  const m = exportManifest({ settings, known, skills: [], archived: [], presets: [], agents: ['qa.md', 'Explore.md', 'notes.txt'], now: 0 })
  assert.deepEqual(m.agents, ['Explore.md', 'qa.md'])
  assert.deepEqual(planSetup(m, { kit: '/k/kit' }).find(s => s.kind === 'agents'), { kind: 'agents', names: ['Explore.md', 'qa.md'] })
  // A manifest from before agents travelled still plans a setup.
  const { agents, ...old } = m
  assert.deepEqual(planSetup(old, { kit: '/k/kit' }).find(s => s.kind === 'agents').names, [])
})

test('the newest vsix is picked by version, not by name', () => {
  assert.equal(newestVsix(['switchboard-0.17.9.vsix', 'switchboard-0.17.10.vsix', 'manifest.json']), 'switchboard-0.17.10.vsix')
  assert.equal(newestVsix(['manifest.json']), undefined)
  assert.equal(newestVsix(['switchboard-0.17.9-beta.vsix', 'switchboard-x.vsix', 'switchboard-1.0.vsix']), undefined)
  assert.equal(newestVsix(['switchboard-0.17.9-beta.vsix', 'switchboard-0.1.0.vsix']), 'switchboard-0.1.0.vsix')
})
